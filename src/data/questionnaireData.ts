export function getDepartmentMetadata(dept: Department | string) {
  if (!dept || !DEPARTMENT_QUESTIONS[dept as Department]) {
    return {
      count: 0,
      subsections: [],
    };
  }

  const questions = DEPARTMENT_QUESTIONS[dept as Department];
  const subsections: string[] = [];

  questions.forEach((q) => {
    if (q.subsection && !subsections.includes(q.subsection)) {
      subsections.push(q.subsection);
    }
  });

  return {
    count: questions.length,
    subsections,
  };
}

